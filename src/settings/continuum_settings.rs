#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub(crate) struct ContinuumSpawnRegion {
    pub(crate) x: i16,
    pub(crate) y: i16,
    pub(crate) radius: u16,
}

impl ContinuumSpawnRegion {
    pub(crate) fn parse(raw: u32) -> Self {
        Self {
            x: sign_extend_bits(raw & 0x03ff, 10) as i16,
            y: sign_extend_bits((raw >> 10) & 0x03ff, 10) as i16,
            radius: ((raw >> 20) & 0x01ff) as u16,
        }
    }

    #[cfg_attr(not(test), allow(dead_code))]
    pub(crate) fn is_configured(self) -> bool {
        self.x != 0 || self.y != 0 || self.radius != 0
    }
}
